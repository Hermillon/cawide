use cawide_protocol::types::{ForgeCapabilities, ForgeKind};

pub fn default_capabilities(kind: ForgeKind) -> ForgeCapabilities {
    match kind {
        ForgeKind::GitHub => ForgeCapabilities {
            pull_requests: true,
            inline_comments: true,
            multiline_comments: true,
            suggestions: true,
            request_changes: true,
            resolve_threads: true,
            reply_to_threads: true,
            auto_merge: true,
            drafts: true,
            checks: true,
            reviewers_by_login: true,
            reopen: true,
            ssh_key_upload: true,
        },
        ForgeKind::GitLab => ForgeCapabilities {
            pull_requests: true,
            inline_comments: true,
            multiline_comments: true,
            suggestions: true,
            request_changes: true,
            resolve_threads: true,
            reply_to_threads: true,
            auto_merge: true,
            drafts: true,
            checks: true,
            reviewers_by_login: true,
            reopen: true,
            ssh_key_upload: true,
        },
        ForgeKind::Gitea => ForgeCapabilities {
            pull_requests: true,
            inline_comments: true,
            multiline_comments: false,
            suggestions: false,
            request_changes: true,
            resolve_threads: false,
            reply_to_threads: false,
            auto_merge: true,
            drafts: true,
            checks: true,
            reviewers_by_login: true,
            reopen: true,
            ssh_key_upload: true,
        },
        ForgeKind::Bitbucket => ForgeCapabilities {
            pull_requests: true,
            inline_comments: true,
            multiline_comments: false,
            suggestions: false,
            request_changes: true,
            resolve_threads: true,
            reply_to_threads: true,
            auto_merge: false,
            drafts: false,
            checks: true,
            reviewers_by_login: false,
            reopen: false,
            ssh_key_upload: true,
        },
        ForgeKind::AzureDevOps => ForgeCapabilities {
            pull_requests: true,
            inline_comments: true,
            multiline_comments: true,
            suggestions: false,
            request_changes: true,
            resolve_threads: true,
            reply_to_threads: true,
            auto_merge: true,
            drafts: true,
            checks: true,
            reviewers_by_login: false,
            reopen: true,
            ssh_key_upload: false,
        },
        ForgeKind::Generic => ForgeCapabilities {
            pull_requests: false,
            inline_comments: false,
            multiline_comments: false,
            suggestions: false,
            request_changes: false,
            resolve_threads: false,
            reply_to_threads: false,
            auto_merge: false,
            drafts: false,
            checks: false,
            reviewers_by_login: false,
            reopen: false,
            ssh_key_upload: false,
        },
    }
}
